from __future__ import annotations

from typing import Any

from .config import WandbConfig


class RunLogger:
    def __init__(
        self,
        config: WandbConfig,
        resolved_config: dict[str, Any],
        is_main_process: bool,
        run_id: str | None = None,
    ) -> None:
        self.run: Any = None
        if not config.enabled or not is_main_process:
            return
        import wandb

        self.run = wandb.init(
            entity=config.entity,
            project=config.project,
            name=config.name,
            group=config.group,
            tags=config.tags,
            mode=config.mode,
            config=resolved_config,
            id=run_id,
            resume="allow" if run_id else None,
        )

    def log(self, metrics: dict[str, Any], step: int | None = None) -> None:
        if self.run is not None:
            self.run.log(metrics, step=step)

    def log_grid(
        self, path: str, caption: str, step: int, key: str = "validation/sample_preview"
    ) -> None:
        if self.run is not None:
            import wandb

            self.run.log({key: wandb.Image(path, caption=caption)}, step=step)

    def finish(self) -> None:
        if self.run is not None:
            self.run.finish()
